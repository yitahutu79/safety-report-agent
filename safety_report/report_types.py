def report_profile(report_type, facility_profile):
    info = REPORT_TYPES.get(report_type)
    if not info:
        raise ValueError('报告类型无效')
    if report_type == DEFAULT_TYPE:
        return {**facility_profile, 'report_type': report_type, 'report_name': info['name'],
                'confirmed_structure': info['confirmed_structure']}
    headings = []
    for title, subheadings in info['chapters']:
        headings.append({'text': title, 'level': 1})
        headings.extend({'text': heading, 'level': 2} for heading in subheadings)
    digest = hashlib.sha256(json.dumps(headings, ensure_ascii=False, sort_keys=True).encode()).hexdigest()
    return {'report_type': report_type, 'report_name': info['name'], 'confirmed_structure': False,
            'guidance': info.get('guidance', ''),
            'headings': headings, 'sections': [], 'table_count': 0, 'image_resources': 0, 'sha256': digest}
